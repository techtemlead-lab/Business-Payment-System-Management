use App\Http\Controllers\WebsiteController;
use App\Http\Controllers\WithdrawalRequestController;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Route;
use Inertia\Inertia;

Route::get('/', [WebsiteController::class, 'home'])->name('home');
Route::get('/pages/{slug}', [WebsiteController::class, 'page'])->name('website.page');
Route::get('/website/media/{key}', [WebsiteController::class, 'image'])->whereUuid('key')->name('website.media');
Route::get('/sitemap.xml', [WebsiteController::class, 'sitemap'])->name('website.sitemap');
Route::middleware('guest')->group(function () {
    Route::get('/request-dealership', [DealershipRequestController::class, 'create'])->name('dealership.request');
    Route::post('/request-dealership', [DealershipRequestController::class, 'store'])->middleware('throttle:5,10,post-request-dealership:');
    Route::get('/login', fn () => Inertia::render('Login'))->name('login');
    Route::post('/login', [AuthController::class, 'login'])->middleware('throttle:login');
    Route::get('/forgot-password', fn () => Inertia::render('ForgotPassword'))->name('password.request');
    Route::post('/forgot-password', [AuthController::class, 'forgot'])->middleware('throttle:5,1,post-forgot-password:')->name('password.email');
    Route::get('/reset-password/{token}', fn (Request $r, string $token) => Inertia::render('ResetPassword', ['token' => $token, 'email' => $r->query('email')]))->name('password.reset');
    Route::post('/reset-password', [AuthController::class, 'reset'])->middleware('throttle:5,1,post-reset-password:')->name('password.update');
    Route::post('/demo-login', [AuthController::class, 'demo'])->middleware('throttle:10,1,post-demo-login:');
});
Route::middleware('auth')->group(function () {
    Route::post('/logout', [AuthController::class, 'logout']);
    Route::get('/two-factor', fn () => Inertia::render('TwoFactor'));
    Route::post('/two-factor', [AuthController::class, 'verifyMfa'])->middleware('throttle:5,1,post-two-factor:');
    Route::get('/security', [AuthController::class, 'security']);
    Route::post('/security/setup', [AuthController::class, 'beginMfa'])->middleware('throttle:5,1,post-security-setup:');
    Route::post('/security/enable', [AuthController::class, 'enableMfa'])->middleware('throttle:5,1,post-security-enable:');
    Route::post('/confirm-password', [AuthController::class, 'confirm'])->middleware('throttle:5,1,post-confirm-password:');
    Route::middleware('workspace')->group(function () {
        Route::get('/website/customize', [WebsiteController::class, 'edit'])->name('website.customize');
        Route::put('/website/draft', [WebsiteController::class, 'save'])->middleware('throttle:60,1,website-draft:')->name('website.save');
        Route::post('/website/publish', [WebsiteController::class, 'publish'])->name('website.publish');
        Route::post('/website/restore/{version}', [WebsiteController::class, 'restore'])->name('website.restore');
        Route::delete('/website/schedule', [WebsiteController::class, 'cancelSchedule'])->name('website.schedule.cancel');
        Route::get('/website/preview', [WebsiteController::class, 'preview'])->name('website.preview');
        Route::post('/website/media', [WebsiteController::class, 'upload'])->middleware('throttle:20,1,website-upload:')->name('website.upload');
        Route::patch('/website/media/{key}', [WebsiteController::class, 'updateMedia'])->whereUuid('key')->name('website.media.update');
        Route::get('/dashboard', [DashboardController::class, 'dashboard'])->name('dashboard');
        Route::get('/rewards/earnings', [EarningsController::class, 'index'])->name('earnings.index');
        Route::get('/referrals', [ReferralController::class, 'index'])->name('referrals.index');
        Route::get('/referrals/options', [ReferralController::class, 'options'])->middleware('throttle:60,1,referral-options:')->name('referrals.options');
        Route::patch('/dealers/{dealer}/referrer', [ReferralController::class, 'update'])->middleware('throttle:20,1,referrer-update:')->name('referrals.update');
        Route::post('/rules/{version}/activate', [RuleController::class, 'activate'])->middleware('throttle:10,1,rule-activation:')->name('rules.activate');
        Route::get('/dealership-requests', [DealershipRequestController::class, 'index']);
        Route::patch('/dealership-requests/{dealershipRequest}', [DealershipRequestController::class, 'update'])->middleware('throttle:20,1,patch-dealership-requests-dealershipRequest:');
        Route::get('/dealers', [DealerController::class, 'dealers']);
        Route::post('/dealers', [DealerController::class, 'createDealer']);
        Route::get('/dealers/{dealer}', [DealerController::class, 'showDealer']);
        Route::patch('/dealers/{dealer}', [DealerController::class, 'updateDealer']);
        Route::post('/dealers/{dealer}/status', [DealerController::class, 'statusDealer'])->middleware('throttle:20,1,post-dealers-dealer-status:');
        Route::get('/rules', [RuleController::class, 'rules']);
        Route::post('/rules', [RuleController::class, 'saveRule']);
        Route::post('/rules/preview', [RuleController::class, 'preview'])->middleware('throttle:60,1,post-rules-preview:');
        Route::get('/operating-mode', [ModeController::class, 'mode']);
        Route::post('/operating-mode', [ModeController::class, 'changeMode'])->middleware('throttle:10,1,post-operating-mode:');
        Route::post('/ranks', [ModeController::class, 'createRank']);
        Route::post('/ranks/{rank}/approve', [ModeController::class, 'approveRank'])->middleware('throttle:10,1,post-ranks-rank-approve:');
        Route::get('/ledger', [LedgerController::class, 'ledger']);
        Route::get('/purchases', [PurchaseController::class, 'index']);
        Route::post('/purchases', [PurchaseController::class, 'store'])->middleware('throttle:20,1,post-purchases:');
        Route::post('/purchases/{purchase}/cancel', [PurchaseController::class, 'cancel'])->middleware('throttle:20,1,post-purchases-purchase-cancel:');
        Route::get('/payouts', [PayoutController::class, 'payouts']);
        Route::post('/payouts', [PayoutController::class, 'requestPayout'])->middleware('throttle:5,1,post-payouts:');
        Route::post('/withdrawal-requests', [WithdrawalRequestController::class, 'store'])->middleware('throttle:5,1,post-withdrawal-requests:');
        Route::patch('/withdrawal-requests/{withdrawalRequest}', [WithdrawalRequestController::class, 'update'])->middleware('throttle:20,1,patch-withdrawal-requests-withdrawalRequest:');
        Route::post('/withdrawal-requests/{withdrawalRequest}/release', [WithdrawalRequestController::class, 'release'])->middleware('throttle:5,1,post-withdrawal-requests-withdrawalRequest-release:');
        Route::get('/audit', [AuditController::class, 'audit']);
        Route::get('/reports', [ReportController::class, 'reports']);
        Route::get('/reports/export', [ReportController::class, 'export']);
        Route::get('/settings', [SettingsController::class, 'settings']);
        Route::patch('/settings', [SettingsController::class, 'saveSettings']);
        Route::get('/hierarchy', [NetworkController::class, 'hierarchy']);
    });
});
